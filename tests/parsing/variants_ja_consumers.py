"""Prototype learning rules for compound B (scope P6) — how hard a sentence counts once B makes compounds, in the
unknowns counters (evaluators.py "analyzer"; evaluators_ja_consumers.py "sentence_corpus", "junban") and in
Junban's own count beside a card (reposition._place_the_rest -> match.unknowns_beside, which the "junban" counter
mirrors — so the mirror and the app stay in step). Each runs B (variants_ja_tokens.py) underneath: without B
there is no compound to count.

    iii        B + (iii): a compound whose parts are all no unknown is no unknown (Compound_Join_Measurement §8)
    giveback   B + give-back with the R flag (§12.2, §12.5): a compound below the list's cut-off and not known
               is counted as its parts when every part is free; one with a bound part stays one unit (千載一遇)
    leans      the approved package (§12.7): compound-b + iii + giveback + r2q-same

SUPERSEDED 2026-09-29 (the compound build): the app runs its own learning rule now (analyzer.LearningView — the
analyzer, 例文 and Junban count through it), so iii, giveback and leans apply it a second time on top of it. Kept as
history, not as a measurement: a plain scorecard run measures the rule as built.

A part is "no unknown" by the consumer's OWN verdict on a token (the analyzer and 例文: no Japanese, ignored,
known, or read through its known word — U9; Junban: no Japanese, one character, ignored or known). The cut-off is
the snapshot's (library_frequency.json settings.min_count); a compound's uses are the library's under B, frozen in
data/variants/compounds.json (the snapshot can't hold them: today the compounds don't exist).

Not simulated (v1): anything list-level — the rows B adds and removes, (iii)'s half score, give-back crediting
parts on the list, the band slider: every list a layer reads is the snapshot's, generated by today's code.
Junban's "i+1 first" pass sees B's units but no give-back. The parts a compound gives back are its headword read
alone (candidates.json — the build plan's "each spelling re-read once"), not the parts in context.
"""
import contextlib
import json
import os
from unittest import mock

from app import analyzer
from tests.parsing import harness
from tests.parsing.variants import VARIANTS, variant
from tests.parsing.variants_ja_tokens import compound_of, table

_FLOOR = {}


def cut_off():
    """The list's cut-off — library_frequency.json settings.min_count of the snapshot the compound counts were
    measured on (harness.SETTINGS_SNAPSHOT): a word needs that many uses to be listed."""
    if not _FLOOR:
        path = os.path.join(harness.DATA, harness.SETTINGS_SNAPSHOT, "ja", "library_frequency.json")
        with open(path, encoding="utf-8") as handle:
            _FLOOR["floor"] = json.load(handle)["settings"]["min_count"]
    return _FLOOR["floor"]


def _has(text):
    return analyzer.has_target_language(str(text), "ja")


def counting_view(tokens, unknown_of, giveback, iii):
    """(tokens as the consumer counts them, keys of compounds that are no unknown). A compound of B is given back
    — replaced by its parts — when it is below the cut-off, not known as a whole (`unknown_of` says it would be an
    unknown) and every part is free; otherwise it stays one unit, and with (iii) it is no unknown when no part of
    it would be one. `unknown_of(token)` is the consumer's own verdict."""
    library, floor = table()["library"], cut_off()
    out, readable = [], set()
    for token in tokens:
        entry = compound_of(token)
        if entry is None:
            out.append(token)
            continue
        parts = [(part.lemma, part.reading, part.surface, part.surface) for part in entry.parts]
        if (giveback and library.get(f"{entry.lemma}|{entry.reading}", 0) < floor and unknown_of(token)
                and all(part.free for part in entry.parts)):
            out.extend(parts)
            continue
        if iii and not any(unknown_of(part) for part in parts):
            readable.add((entry.lemma, entry.reading))
        out.append(token)
    return out, readable


# --- the consumers' verdicts on one token ------------------------------------------------------------------------ #
def analyzer_verdict(ctx, sets):
    """analyzer.main's (and sentence_corpus.collect's) test for one token of a sentence, the target aside: a word
    with Japanese, not ignored, not known, not read through its known word (U9)."""
    known_tuples, known_lemmas, ignore = sets
    joins = analyzer.affix_joins()
    tagger = ctx.tokenizer("ja").tagger

    def unknown_of(token):
        lemma, reading, surface = str(token[0]), token[1], token[2]
        if not (_has(lemma) or _has(surface)):
            return False
        if lemma in ignore or (lemma, reading) in known_tuples or lemma in known_lemmas:
            return False
        if lemma in joins:
            base = analyzer.see_through_base(lemma, reading, tagger, joins)
            if base is not None and (base in known_tuples or base[0] in known_lemmas or base[0] in ignore):
                return False
        return True
    return unknown_of


def junban_verdict(ctx, sets):
    """reposition._place_the_rest's `unknown`: Japanese, two characters or more, neither ignored nor known."""
    known_tuples, known_lemmas, ignore = sets

    def unknown_of(token):
        lemma, reading, surface = str(token[0]), token[1], token[2]
        if not (_has(lemma) or _has(surface)) or len(lemma) == 1:
            return False
        return not (lemma in ignore or lemma in known_lemmas or (lemma, reading) in known_tuples)
    return unknown_of


# --- a counter run on the counting view -------------------------------------------------------------------------- #
class _ViewTokenizer:
    """The run's JapaneseTokenizer as a consumer counts through it: the same tokens, each sentence's through
    `counting_view`, every sentence read before the first is handed out (so (iii)'s keys are known in time)."""

    def __init__(self, real, view):
        self._real, self._view = real, view

    @property
    def tagger(self):
        return self._real.tagger

    def tokenize_sentences(self, text, pieces=None):
        return iter([(s_text, self._view(tokens)) for s_text, tokens in self._real.tokenize_sentences(text, pieces)])

    def tokenize(self, text, pieces=None):
        return [token for _s, tokens in self.tokenize_sentences(text, pieces) for token in tokens]


class _ViewContext:
    """The run's Context, with the Japanese tokenizer a _ViewTokenizer — everything else is the run's."""

    def __init__(self, ctx, tokenizer):
        self._ctx, self._tokenizer = ctx, tokenizer

    def tokenizer(self, lang, script="asis"):
        return self._tokenizer if lang == "ja" else self._ctx.tokenizer(lang, script)

    def __getattr__(self, name):
        return getattr(self._ctx, name)


def _on_view(counter, verdict, giveback, iii):
    """`counter` (a registered unknowns counter, unchanged) run on the counting view: its tokenizer yields the
    compounds as the rule counts them, and its known sets gain the compounds (iii) makes no unknown."""
    def count(case, ctx, sets):
        if case.lang != "ja":
            return counter(case, ctx, sets)
        unknown_of = verdict(ctx, sets)
        extended = (set(sets[0]), sets[1], sets[2])

        def view(tokens):
            out, readable = counting_view(tokens, unknown_of, giveback, iii)
            extended[0].update(readable)
            return out
        return counter(case, _ViewContext(ctx, _ViewTokenizer(ctx.tokenizer("ja"), view)), extended)
    return count


def _junban_count(real, giveback, iii):
    """match.unknowns_beside as reposition._place_the_rest calls it, on the counting view: its own `unknown` (no
    side effects) is the verdict, for the compound as a whole and for each part."""
    def unknowns_beside(word, raw, tokenize, unknown):
        readable = set()

        def counted(text):
            out, found = counting_view(list(tokenize(text)), unknown, giveback, iii)
            readable.update(found)
            return out
        return real(word, raw, counted,
                    lambda token: (str(token[0]), token[1]) not in readable and unknown(token))
    return unknowns_beside


@contextlib.contextmanager
def learning_rule(giveback, iii):
    """The unknowns counters and Junban's count beside a card, on the counting view, for the duration."""
    from modules.junban import match
    from tests.parsing import evaluators_ja_consumers  # noqa: F401  (registers "sentence_corpus", "junban")
    from tests.parsing.evaluators import UNKNOWN_COUNTERS
    table()
    swapped = {name: _on_view(UNKNOWN_COUNTERS[name], junban_verdict if name == "junban" else analyzer_verdict,
                              giveback, iii)
               for name in ("analyzer", "sentence_corpus", "junban")}
    with mock.patch.dict(UNKNOWN_COUNTERS, swapped), \
            harness.patched(match, "unknowns_beside", _junban_count(match.unknowns_beside, giveback, iii)):
        yield


@variant("iii",
         "compound-b + (iii): a compound whose parts are all no unknown (known, ignored, read through a known word) "
         "is no unknown in a sentence — in the analyzer's, 例文's and Junban's counts (Compound_Join_Measurement §8).")
def _iii():
    with VARIANTS["compound-b"].manager(), learning_rule(giveback=False, iii=True):
        yield


@variant("giveback",
         "compound-b + give-back with the R flag: a compound under the list's cut-off, not known, counts as its "
         "parts when every part is free (トランスジェンダー = 2); a bound part keeps it one unit (千載一遇) — in the "
         "three counts (§12.2, §12.5).")
def _giveback():
    with VARIANTS["compound-b"].manager(), learning_rule(giveback=True, iii=False):
        yield


@variant("leans",
         "The approved package (§12.7): compound-b + iii + giveback (R flag) + r2q-same, together.")
def _leans():
    with VARIANTS["compound-b"].manager(), VARIANTS["r2q-same"].manager(), \
            learning_rule(giveback=True, iii=True):
        yield


# --- F8b read literally: Junban's known test for a card written in kana alone (Parsing_Fixes_Plan F8) ---------- #
# Built (2026-09-27): the one word read alone counts only as a (lemma, reading) the learner knows, never as a single
# kana (reposition.is_known_word). These two are the plan's words taken literally, kept to show what each costs.
def _kana_known_test(stem_by_letters):
    """reposition.is_known_word with a card written in kana alone known only by its own letters: the word on the
    known / ignore lists — and, with `stem_by_letters`, read alone as ONE word + ONE ending as card_key reads it,
    that word's own letters (its surface) on them."""
    from app.anki_match import _KANA_ONLY_RE
    from modules.junban import match, reposition
    real = reposition.is_known_word

    def is_known_word(word, known, known_lemmas, ignore, tokenize, known_tuples=None):
        if not (word and _KANA_ONLY_RE.match(word)):
            return real(word, known, known_lemmas, ignore, tokenize, known_tuples)
        if word in known_lemmas or word in ignore:
            return True
        tokens = list(tokenize(word)) if (tokenize and stem_by_letters) else []
        token = match.one_word(tokens) if len(tokens) == 2 else None
        return token is not None and (token[2] in known_lemmas or token[2] in ignore)
    return harness.patched(reposition, "is_known_word", is_known_word)


@variant("kana-letters-only",
         "F8b taken literally: a card written in kana alone is never read alone for 'known' — only its own letters "
         "on the known / ignore lists (no ending taken off: ホッとする, ぐっと).")
def _kana_letters_only():
    with _kana_known_test(stem_by_letters=False):
        yield


@variant("kana-as-card-key",
         "F8b as card_key reads a kana card: its own letters, or read alone as ONE word + ONE ending, that word's "
         "own letters (surface) on the known / ignore lists — never a bare kana word read alone.")
def _kana_as_card_key():
    with _kana_known_test(stem_by_letters=True):
        yield
